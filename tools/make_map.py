import os
import re
import subprocess
import datetime


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


files = sorted(
    os.path.join(d, f).replace('\\', '/')
    for d, _, fs in os.walk('lib')
    for f in fs
    if f.endswith('.dart')
)

try:
    commit = subprocess.check_output(
        ['git', 'log', '-1', '--format=%h %s'], text=True
    ).strip()
except Exception:
    commit = 'unknown'

class_re = re.compile(r'^class\s+(\w+)', re.M)
screen_re = re.compile(r'\b([A-Z]\w*(?:Screen|Page))\s*\(')
imp_re = re.compile(r"import\s+'([^':]+\.dart)'")

deps = []
try:
    sec = False
    for line in read('pubspec.yaml').split('\n'):
        if line.startswith('dependencies:'):
            sec = True
            continue
        if sec:
            if line and not line.startswith((' ', '#')):
                break
            s = line.strip()
            if s and not s.startswith('#'):
                deps.append(s)
except Exception:
    pass

out = []
out.append('# AMOLE APP - PROJECT MAP (auto-generated)')
out.append('')
out.append('Generated: ' + datetime.date.today().isoformat())
out.append('Last commit when generated: ' + commit)
out.append('')
out.append('DO NOT edit this file by hand. Regenerate it with:')
out.append('    python3 tools/make_map.py')
out.append('')
out.append('## How AI should use this file')
out.append('- Read PROJECT_STATUS.md first (rules, stage, history), then this map.')
out.append('- This map shows WHICH file does what and how screens connect. It does NOT show full behavior.')
out.append('- Before changing a file, open and read that file fully. Do not guess from this map.')
out.append('- "opens" = screens this file navigates to or builds. "uses" = widgets/data/models it imports.')
out.append('')
if deps:
    out.append('## Dependencies (pubspec.yaml)')
    for d in deps:
        out.append('- ' + d)
    out.append('')

folders = {}
for p in files:
    folders.setdefault(os.path.dirname(p), []).append(p)

out.append('## Files (%d total)' % len(files))
out.append('')
for folder in sorted(folders):
    out.append('### ' + folder + '/')
    for p in folders[folder]:
        src = read(p)
        n = src.count('\n') + 1
        classes = class_re.findall(src)
        screens = sorted(set(screen_re.findall(src)) - set(classes))
        uses = sorted(set(
            os.path.basename(i)
            for i in imp_re.findall(src)
            if any(x in i for x in ('widgets/', 'data/', 'models/'))
        ))
        row = '- **%s** (%d lines)' % (os.path.basename(p), n)
        if classes:
            row += ' | classes: ' + ', '.join(classes)
        if screens:
            row += ' | opens: ' + ', '.join(screens)
        if uses:
            row += ' | uses: ' + ', '.join(uses)
        out.append(row)
    out.append('')

with open('PROJECT_MAP.md', 'w', encoding='utf-8') as f:
    f.write('\n'.join(out))

print('झाले! PROJECT_MAP.md बनली. एकूण files:', len(files))